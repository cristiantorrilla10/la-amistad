const botonesCategorias = document.querySelectorAll(".categorias button");
const destacados = document.getElementById("destacados");

const numeroWhatsApp = "5491112345678";

function mostrarProductos(categoria = "Todos") {
    
    bienvenida.style.display = "none";
    destacados.style.display = "none";

    listaProductos.innerHTML = "";

    const productosFiltrados =
        categoria === "Todos"
            ? productos
            : productos.filter(producto => producto.categoria === categoria);
    
    if (categoria === "Todos") {
        tituloCategoria.textContent = "Todos los productos";
    } else {
        tituloCategoria.textContent = categoria;
    }

    productosFiltrados.forEach(producto => {

        const precio = producto.precio
            ? producto.precio
            : "Consultar precio";

        const mensaje = `Hola, quería consultar por ${producto.nombre}.`;

        const tarjeta = document.createElement("div");
        tarjeta.classList.add("producto");

        tarjeta.innerHTML = `
            <div class="foto-producto">
                <img src="imagenes/${producto.imagen}" alt="${producto.nombre}">
            </div>

            <h3>${producto.nombre}</h3>

            <p class="precio">${precio}</p>

            <a class="boton-producto"
               href="https://wa.me/${numeroWhatsApp}?text=${encodeURIComponent(mensaje)}"
               target="_blank">
                💬 Consultar por WhatsApp
            </a>
        `;

        listaProductos.appendChild(tarjeta);
    });
}

